#define SS_MAX_WIDTH        (1920ul)
#define SS_MAX_HEIGHT       (1200ul)
#define SS_LINE_SIZE        (16384)// 0x4000
#define SS_READ_SIZE        (64)//< SPI_BURST_MAX // (65536 * 30) Cindy: This is for 4 lines * 30 = 120 lines
#define SS_READ_TIMES       (SS_MAX_HEIGHT * SS_LINE_SIZE / SS_READ_SIZE)// Cindy because 1200 lines /120 lines = 10, capture 10 times

#define SS_RBUF_SIZE        (SS_READ_SIZE + 8)
#define SS_MBUF_SIZE        (SS_MAX_HEIGHT * SS_LINE_SIZE + 8)
#define SS_IBUF_SIZE        (SS_MAX_WIDTH * SS_MAX_HEIGHT * 3 + 100)
UINT8 halC789Ctrl_ScreenSaveToImage(UINT32 xPos, UINT32 yPos, UINT32 nWidth, UINT32 nHeight)
{// R70G2_Bruce#0022
#ifndef SIMULATOR_ISCALER
    if(halC789Ctrl_SemaphoreTake(__FUNCTION__) == TRUE)
    {
        if (((xPos + nWidth) > SS_MAX_WIDTH) || ((yPos + nHeight) > SS_MAX_HEIGHT))
        {
            LOG_MSG(db_HAL_RESERVED17, "%s()(xPos + nWidth) = %d > SS_MAX_WIDTH = %d fail !!!\r\n", __func__, (xPos + nWidth), SS_MAX_WIDTH);
            LOG_MSG(db_HAL_RESERVED17, "%s()(yPos + nHeight) = %d > SS_MAX_HEIGHT = %d fail !!!\r\n", __func__, (yPos + nHeight), SS_MAX_HEIGHT);
            halC789Ctrl_SemaphoreGive(__FUNCTION__);
            return(0);
        }

        unsigned char *readBuff = (unsigned char *)malloc(SS_READ_SIZE + 8);
        unsigned char *memoryBuff = (unsigned char *)malloc(SS_MAX_HEIGHT * SS_LINE_SIZE + 8);
        unsigned char *imageBuff = (unsigned char *)malloc(SS_MAX_WIDTH * SS_MAX_HEIGHT * 3 + 100);
        if ((readBuff == NULL) || (memoryBuff == NULL) || (imageBuff == NULL))
        {
            LOG_MSG(db_HAL_RESERVED17, "%s() data = %d, memoryBuff = %d, imageBuff = %d fail !!!\r\n", __func__, readBuff, memoryBuff, imageBuff);
            free(readBuff);
            free(memoryBuff);
            free(imageBuff);
            halC789Ctrl_SemaphoreGive(__FUNCTION__);
            return(0);
        }
        //memset(readBuff, 0x00, sizeof(readBuff));
        //memset(memoryBuff, 0x00, sizeof(memoryBuff));
        //memset(imageBuff, 0x00, sizeof(imageBuff));

        LOG_MSG(db_HAL_RESERVED17, "%s(%d, %d, %d, %d)\r\n", __func__, xPos, yPos, nWidth, nHeight);
        LOG_MSG(db_HAL_RESERVED17, "%s() SS_MAX_WIDTH=%d.\r\n", __func__, SS_MAX_WIDTH);
        LOG_MSG(db_HAL_RESERVED17, "%s() SS_MAX_HEIGHT=%d.\r\n", __func__, SS_MAX_HEIGHT);
        LOG_MSG(db_HAL_RESERVED17, "%s() SS_READ_SIZE=%d.\r\n", __func__, SS_READ_SIZE);
        LOG_MSG(db_HAL_RESERVED17, "%s() SS_READ_TIMES=%d.\r\n", __func__, SS_READ_TIMES);

        UINT32 isfld0 = dvC789_Read(B9_ISFLD0);
        UINT8 imwi = (UINT8)dvC789_Read(B9_IMWI) & 0x03;
        UINT8 cpudtctl = 0;
        imwi = abs(3 * imwi - 2);
        LOG_MSG(db_HAL_RESERVED17, "%s() isfld0=0x%x, imwi = %d.\r\n", __func__, isfld0, imwi);

        UINT32 i = 0, j = 0, x = 0, y = 0;
        UINT32 memoryIdx = 0, imageIdx = 0;
        FILE *fp;
        fp = fopen("/home/root/Log.txt", "w+");
        for (i = 0; i < SS_READ_TIMES; i ++)
        {// spi burst read data to memoryBuff
            dvC789_WriteToBuffer(B0_CPURAD, isfld0 + i * SS_READ_SIZE);
            dvC789_WriteToBuffer(B0_CPUDTCTL, 0x01);
            dvC789_Buffer_Flush();
            cpudtctl = 0x08;
            while ((cpudtctl & 0x08) != 0)
            {
            #if 1
                fprintf(fp, "i=%d:\r\n", i);
            #else
                usleep(10 * 1000);
            #endif
                cpudtctl = (UINT8) dvC789_Read(B0_CPUDTCTL);
            }
            dvC789_BurstRead_FixedAdd(B0_CPUDT, SS_READ_SIZE, readBuff);
            //memcpy(&memoryBuff[i * SS_READ_SIZE], readBuff, SS_READ_SIZE);
            for (j = 0; j < SS_READ_SIZE; j++)
            {
                memoryBuff[i * SS_READ_SIZE + j] = readBuff[j];
                //fprintf(fp, "m[%d]=%d\r\n", i * SS_READ_SIZE + j, memoryBuff[i * SS_READ_SIZE + j]);
            }
        }

        for (y = yPos; y < (yPos + nHeight); y ++)
        {// Data tranform from memoryBuff to imageBuff
            for (x = xPos; x < (xPos + nWidth); x ++)
            {
                for (i = 0; i < 3; i ++)// R/G/B index
                {
                    memoryIdx = imwi * 32768 * (y / 4) + 16 * (y % 4);
                    // 12 pixels per 256 Bytes:
                    // R addr: 0, size: 12 * 10 bits,
                    // G addr: 64, size: 12 * 10 bits,
                    // B addr: 128, size: 12 * 10 bits,
                    // Get high 8 bits only
                    if (x % 12 < 6)
                        j = x % 12;// d0[9:2], d1[9:2], d2[9:2], d3[9:2], d4[9:2], d5[9:2], {d3[1:0], d2[1:0], d1[1:0], d0[1:0]}, {d5[1:0], d4[1:0]}
                    else
                        j = x % 12 + 2;// d6[9:2], d7[9:2], d8[9:2], d9[9:2], d10[9:2], d11[9:2], {d9[1:0], d8[1:0], d7[1:0], d6[1:0]}, {d11[1:0], d10[1:0]}
                    memoryIdx = memoryIdx + (x / 12) * 256 + j;// 12 pixels per 256 Bytes
                    memoryIdx = memoryIdx + 64 * i;// addr 0 ~ 63: R, addr 64 ~ 127: G, addr 128 ~ 191: B

                    imageIdx = nWidth * 3 * y + 3 * x + i;
                    imageBuff[imageIdx] = memoryBuff[memoryIdx];
                    fprintf(fp, "m[%d] -> i[%d]=%d.\r\n", memoryIdx, imageIdx, imageBuff[imageIdx]);
                }
            }
        }
        fclose(fp);

        free(readBuff);
        free(memoryBuff);
        LOG_MSG(db_HAL_RESERVED17, "%s() call generatePNG().\r\n", __func__);
        generatePNG(imageBuff, nWidth, nHeight, (char *)"/home/root/osdcapture.png");
        free(imageBuff);
        LOG_MSG(db_HAL_RESERVED17, "%s() generatePNG() complete.\r\n", __func__);
        halC789Ctrl_SemaphoreGive(__FUNCTION__);
    }
    else
    {
        LOG_MSG(db_ALWAYS, "%s() halC789Ctrl_SemaphoreTake() fail !!!\r\n", __func__);
        return(0);
    }
#endif /* SIMULATOR_ISCALER */
    return(1);
}

void halC789Ctrl_Freeze(UINT8 ucEnable)     //A35G2_CDS_Simon_0003
{
    if(halC789Ctrl_SemaphoreTake(__FUNCTION__) == TRUE)
    {
        if(ucEnable)
        {
        	dvC789_Write(BN_MCT, 0x41);

            UINT8 ucISYCT = dvC789_ISYCT_Get();
            ucISYCT &= 0xF0;
            ucISYCT |= 0x02;
            dvC789_ISYCT_Set(ucISYCT);
    	}
    	else //unfreeze
    	{
            UINT8 ucISYCT = dvC789_ISYCT_Get();
            ucISYCT &= 0xF0;
            ucISYCT |= 0x01;
            dvC789_ISYCT_Set(ucISYCT);

        	dvC789_Write(BN_MCT, 0x51);
    	}

        halC789Ctrl_SemaphoreGive(__FUNCTION__);
    }
}


