void halC789Ctrl_BankSync(void) //A70LV_Larry_0318
{
    if(halC789Ctrl_SemaphoreTake(__FUNCTION__) == TRUE)
    {
        dvC789_Write(BN_RGBNK, 0x00);

        halC789Ctrl_SemaphoreGive(__FUNCTION__);
    }
}

