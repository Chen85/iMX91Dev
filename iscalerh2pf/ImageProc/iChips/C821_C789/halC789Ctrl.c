BOOL halC789Ctrl_SemaphoreTake(const char *pcFunc)
{
    BOOL bResult = dvC789_SemaphoreTake(TRUE, pcFunc);

    return bResult;
}

BOOL halC789Ctrl_SemaphoreGive(const char *pcFunc)
{
    BOOL bResult = dvC789_SemaphoreTake(FALSE, pcFunc);

    return bResult;
}

