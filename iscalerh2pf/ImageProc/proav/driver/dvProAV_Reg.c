// ==============================================================================
// FUNCTION NAME: dvPro_RegDump
// DESCRIPTION:
//
//
// Params:
//
// Returns:
//
//
// Modification History
// --------------------
// 2020/02/29, Larry Create
// --------------------
// ==============================================================================
void dvPro_RegDump(UINT8 cBank)
{
    UINT16 wCount = 0;
    UINT32 dwData = 0;
    UINT8  cCount = 0;
    UINT8  acData[32] = {0};
    char   str[256] = {'\0'};
    int    iOffset =0;

    if(m_sPROAV_DUMP[wCount].ulAddress == 0x12345678)
    {
        LOG_MSG(db_ALWAYS, "Proav Reg %s\r\n",  m_sPROAV_DUMP[wCount].cReg);

        wCount++;

        while(1)
        {
            if(m_sPROAV_DUMP[wCount].ulAddress == 0xFFFFFFFF)
            {
                LOG_MSG(db_ALWAYS, "Proav Reg %s\r\n",  m_sPROAV_DUMP[wCount].cReg);
                return;
            }
            else
            {
                uint08 ucRW = GET_REG_RDWR(m_sPROAV_DUMP[wCount].ulAddress);
                uint08 bank = GET_REG_BANK(m_sPROAV_DUMP[wCount].ulAddress);
                uint08 offset = GET_REG_OFFS(m_sPROAV_DUMP[wCount].ulAddress);
                uint8 len = GET_REG_SIZE(m_sPROAV_DUMP[wCount].ulAddress);

                if((cBank == 99) || (cBank == bank))
                {
                    if(ucRW == 0)
                    {
                        LOG_MSG(db_ALWAYS, "%02x %02x %s write only\r\n", bank, offset, m_sPROAV_DUMP[wCount].cReg);
                    }
                    else
                    {
                        dvProAV_AccessRawDataRead(bank, offset, (uint16)len, acData);

                        memset(str, '\0', 256);
                        iOffset = 0;

                        for(cCount = 0; cCount < len; cCount++)
                        {
                            iOffset += sprintf(str + iOffset,"0x%02X ", acData[cCount]);
                        }

                        LOG_MSG(db_ALWAYS, "%02x %02x %s %s\n",bank, offset,  m_sPROAV_DUMP[wCount].cReg, str);
                    }

                    MS_SLEEP(5);
                }
            }

            wCount++;
        }

    }
    else
    {
        return;
    }
}



