void dvVCXO949_DumpRegTable(eVCXO_SEL eVCXOSel)
{
    UINT16 x = 0 ;
    UINT8 Data = 0 ;

    if(eVCXOSel < eVCXO_SEL_LAST)
    {
        (eVCXOSel == eVCXO_SEL_C734) ? (LOG_MSG(db_DV_VCXO, "\r\n\r\nCDCE949(C734) Start")) : (LOG_MSG(db_DV_VCXO, "\r\n\r\nCDCE949(C821) Start"));

        for(x=0 ; x<256 ; x++)
        {
            dvVCXO949_I2C_Read((x|0x80) , &Data , eVCXOSel) ;

            if( x % 16 == 0)
            {
                #if (CURRENT_MAIN_BOARD == CORE_BOARD)
                LOG_MSG(db_DV_VCXO, "\r\n");
                #else
                LOG_MSG(db_DV_VCXO, "\n");
                #endif

                LOG_MSG(db_DV_VCXO, "0x%02X => ", x);
            }

            LOG_MSG(db_DV_VCXO, "[%02X]", Data);
        }

        (eVCXOSel == eVCXO_SEL_C734) ? (LOG_MSG(db_DV_VCXO, "\r\nCDCE949(C734) End\r\n\r\n")) : (LOG_MSG(db_DV_VCXO, "\r\nCDCE949(C821) End\r\n\r\n"));
    }
    else
    {
        dvVCXO949_Write_InitTbl(eVCXO_SEL_C821_WU);
    }
}

